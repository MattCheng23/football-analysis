print('=== 最终比分/半全场（期望贴合+大球覆盖）===')
for no in ['001', '003', '004', '005', '006', '008', '009', '010', '011', '014', '016', '019', '024', '026']:
    lh, la, dr, gr, scs, hts = final[no]
    p = probs(lh, la)
    # 每个比分概率 + 总球数
    parts = []
    for s in scs:
        clean = s.replace('*', '')
        h, a = map(int, clean.split('-'))
        prob = p[(h, a)]
        parts.append(f'{s}({prob*100:.1f}%)')
    # ou 推导：比分总球数概率加权前二
    tg = {}
    for s in scs:
        h, a = map(int, s.replace('*', '').split('-'))
        t = h + a
        tg[t] = tg.get(t, 0) + p[(h, a)]
    srt = sorted(tg.items(), key=lambda x: -x[1])
    ou = '%d·%d' % (min(srt[0][0], srt[1][0]), max(srt[0][0], srt[1][0]))
    mark = '*' if gr == 'C' else ''
    print(f'{no} {dr}{gr} | {" / ".join(parts)} | ht: {" / ".join(hts)} | ou {ou}')
