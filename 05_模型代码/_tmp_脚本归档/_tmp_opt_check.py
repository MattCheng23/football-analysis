# -*- coding: utf-8 -*-
import math, sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

def pois(k, lam): return math.exp(-lam) * lam**k / math.factorial(k)
def probs(lh, la):
    d = {}
    for h in range(9):
        for a in range(9): d[(h, a)] = pois(h, lh) * pois(a, la)
    return d
def dk(k):
    h, a = k; return '胜' if h > a else ('平' if h == a else '负')

# 晚场 9 场：校准后 λ（R299 分联赛偏差 60% 吸收 + 伤停微调）
# 008 英冠+1.2→+0.36/队; 009 瑞超-0.1→≈0; 010 英冠+1.2; 011 挪超0; 014 芬超+1.3→+0.39; 016 英冠; 019/024 西甲+1.2; 026 巴甲+0.5
games = {
    '008': (1.65, 1.35),   # 博尔顿vs普雷斯顿
    '009': (1.35, 1.45),   # 米亚尔比vs天狼星
    '010': (1.95, 1.45),   # 诺维奇vs西布朗
    '011': (1.35, 1.60),   # 奥斯陆vs利勒斯特罗姆
    '014': (0.80, 1.30),   # 玛丽港vs塞伊奈约基
    '016': (1.95, 1.15),   # 谢菲联vs伯明翰
    '019': (1.10, 1.30),   # 阿拉维斯vs赫塔费（修正后：赫塔费更强）
    '024': (1.30, 1.50),   # 塞维利亚vs巴列卡诺（修正后：客队略优）
    '026': (1.00, 1.40),   # 弗鲁米嫩塞vs帕尔梅拉斯
}
cur = {
    '008': ('胜/平', ['1-1','2-1','2-2'], ['平平','平胜','胜平']),
    '009': ('平/负', ['1-2','1-1','2-2'], ['平负','平平','负平']),
    '010': ('胜/平', ['2-1','1-1','2-2'], ['胜胜','平平','胜平']),
    '011': ('负/平', ['1-2','1-1','0-1'], ['平负','平平','负负']),
    '014': ('负',   ['0-2','1-2','1-1*'], ['负负','平负','平平*']),
    '016': ('胜',   ['2-1','2-0','3-1'], ['胜胜','平胜','负胜']),
    '019': ('平/负', ['1-1','0-1','1-2'], ['平平','平负','负负']),
    '024': ('平/负', ['1-2','1-1','0-1'], ['平负','平平','负负']),
    '026': ('平/负', ['1-1','0-1','1-2'], ['平平','平负','负负']),
}

print('=== 晚场 9 场：当前预测 vs 校准λ泊松 ===')
for no in ['008','009','010','011','014','016','019','024','026']:
    lh, la = games[no]
    p = probs(lh, la)
    srt = sorted(p.items(), key=lambda x: -x[1])
    dr, scs, hts = cur[no]
    print(f'--- {no} {dr} (λ {lh}/{la}, 期望{lh+la:.1f}) ---')
    # 当前比分在泊松中的排名
    ranks = []
    for s in scs:
        h, a = map(int, s.replace('*','').split('-'))
        rank = next((i+1 for i,(k,v) in enumerate(srt) if k==(h,a)), '>15')
        ranks.append(f'{s}#{rank}')
    print(f'  当前比分: {" ".join(ranks)}')
    # 主方向概率最高的 TOP5 比分
    main5 = [f'{h}-{a}({v*100:.1f}%)' for (h,a),v in srt if (('胜' in dr and h>a) or ('平' in dr and h==a) or ('负' in dr and h<a))][:5]
    print(f'  主方向TOP5: {" ".join(main5)}')
    # 全局 TOP5
    top5 = [f'{h}-{a}({v*100:.1f}%)' for (h,a),v in srt[:5]]
    print(f'  全局TOP5: {" ".join(top5)}')
    print()
