def build_batch(key, title, model, matches, results, stats):
    ms = "\n".join(m(*x) for x in matches)
    mlookup = {x[0]: (x[3], x[4]) for x in matches}  # no -> (league, lg)
    def rr(x):
        no, teams, score, d, s, h, signal, sc = x
        league, lg = mlookup[no]
        return r(no, teams, league, lg, score, d, s, h, signal, sc)
    rs = "\n".join(rr(x) for x in results)
    return f'''  "{key}": {{
    title: "{title}",
    model: "{model}",
    predictDate: "{key}",
    reviewed: true,
    stats: {{ dir: "{stats[0]}", dirPct: "{stats[1]}", score: "{stats[2]}", scorePct: "{stats[3]}", ht: "{stats[4]}", htPct: "{stats[5]}" }},
    predict: {{
      matches: [
{ms}
      ],
      coldRisk: [], alerts: [], zeroZero: []
    }},
    review: {{
      results: [
{rs}
      ],
      evidence: [], avoidHigh: [], avoidWatch: []
    }}
  }},
'''

