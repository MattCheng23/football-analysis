import math, sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

def pois(k, lam):
    return math.exp(-lam) * lam**k / math.factorial(k)

def top_scores(lh, la, n=8):
    probs = {}
    for h in range(0, 8):
        for a in range(0, 8):
            probs[(h, a)] = pois(h, lh) * pois(a, la)
    top = sorted(probs.items(), key=lambda x: -x[1])[:n]
    win = sum(p for (h, a), p in probs.items() if h > a)
    draw = sum(p for (h, a), p in probs.items() if h == a)
    loss = sum(p for (h, a), p in probs.items() if h < a)
    return top, win, draw, loss

