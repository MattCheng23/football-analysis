# -*- coding: utf-8 -*-
import io

p = r'D:\Cola\足球分析学习\_发布_public\js\data.js'
with io.open(p, 'r', encoding='utf-8') as f:
    s = f.read()

# ht 逐位对应比分方向修复（每位第二字 = 该比分全场方向）
# 005: 1-1→平平, 2-1→胜胜, 1-0→平胜
repl = [
    # 005 首尔
    ('scores: "1-1 / 2-1 / 1-0", ht: "平平/胜胜/胜平", ou: "总进球 2·3"',
     'scores: "1-1 / 2-1 / 1-0", ht: "平平/胜胜/平胜", ou: "总进球 2·3"'),
    # 006 光州: 1-1→平平, 0-1→平负, 0-0→平平 重复！换 0-1→负负(半场0-1)
    ('scores: "1-1 / 0-1 / 0-0", ht: "平平/平负/负负", ou: "总进球 1·2"',
     'scores: "1-1 / 0-1 / 0-0", ht: "平平/负负/平平", ou: "总进球 1·2"'),
    # 008 博尔顿: 2-1→胜胜, 1-1→平平, 2-2→胜平
    ('scores: "2-1 / 1-1 / 2-2", ht: "平平/胜胜/胜平", ou: "总进球 2·3"',
     'scores: "2-1 / 1-1 / 2-2", ht: "胜胜/平平/胜平", ou: "总进球 2·3"'),
    # 011 奥斯陆: 1-1→平平, 1-2→平负, 0-1→平负 重复！0-1→负负
    ('scores: "1-1 / 1-2 / 0-1", ht: "平平/平负/负平", ou: "总进球 2·3"',
     'scores: "1-1 / 1-2 / 0-1", ht: "平平/平负/负负", ou: "总进球 2·3"'),
    # 019 阿拉维斯: 1-1→平平, 2-1→胜胜, 1-0→平胜
    ('scores: "1-1 / 2-1 / 1-0", ht: "胜胜/平平/平胜", ou: "总进球 2·3"',
     'scores: "1-1 / 2-1 / 1-0", ht: "平平/胜胜/平胜", ou: "总进球 2·3"'),
    # 024 塞维利亚: 1-1→平平, 2-1→胜胜, 2-2→胜平
    ('scores: "1-1 / 2-1 / 2-2", ht: "平平/胜胜/平胜", ou: "总进球 2·3"',
     'scores: "1-1 / 2-1 / 2-2", ht: "平平/胜胜/胜平", ou: "总进球 2·3"'),
    # 026 弗鲁米嫩塞: 1-1→平平, 0-1→平负, 1-2→负负
    ('scores: "1-1 / 0-1 / 1-2", ht: "平负/平平/负负", ou: "总进球 1·2"',
     'scores: "1-1 / 0-1 / 1-2", ht: "平平/平负/负负", ou: "总进球 1·2"'),
    # 004 神户: 1-1→平平, 2-1→胜胜, 2-2→胜平 ✓ (已对)
    # 010 诺维奇: 2-1→胜胜, 2-2→平平, 1-1→平平 重复！2-2→胜平? 2-2全场平→第二字平。2-2→平平,1-1→平平重复
    ('scores: "2-1 / 2-2 / 1-1", ht: "胜胜/平平/胜平", ou: "总进球 3·4"',
     'scores: "2-1 / 2-2 / 1-1", ht: "胜胜/平平/平平", ou: "总进球 3·4"'),
]
cnt = 0
for old, new in repl:
    n = s.count(old)
    if n != 1:
        print('WARN count=%d -> %s' % (n, old[:50]))
        continue
    s = s.replace(old, new)
    cnt += 1
with io.open(p, 'w', encoding='utf-8') as f:
    f.write(s)
print('replaced: %d / %d' % (cnt, len(repl)))
